/**
 * Matchday — the ticket email.
 *
 * A match ticket, sent before kickoff: who plays, when, where, and the
 * ticket itself — seat, gate, and the scannable code. The code is a PNG
 * Image (Svg is an error in Email), generated at build time from the ticket
 * number in fixture.ts and embedded as a data: URI, so the email is
 * self-contained. The fan's name is a MergeTag for the sending service.
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  Button,
  Column,
  Divider,
  Email,
  Grid,
  Heading,
  Image,
  Link,
  List,
  ListItem,
  Menu,
  MergeTag,
  Row,
  Section,
  Social,
  Span,
  Text,
  token,
} from "@hyper-elements/react";
import { FIXTURE, type Fixture } from "../fixture.js";
import { homeTheme } from "../theme.js";
import { WEB_FONT_FACES } from "../fonts.js";
import { InfoPill, TeamBadge } from "../components.js";
import { codeDataUri } from "../code.js";

// The code PNG, generated by scripts/generate-code-png.ts from the ticket
// number. Read at module load so `hyper-elements check` sees the same file
// the render writes.
const CODE_SRC = (() => {
  try {
    const png = readFileSync(
      join(dirname(fileURLToPath(import.meta.url)), "..", "..", "assets", "ticket-code.png"),
    );
    return `data:image/png;base64,${png.toString("base64")}`;
  } catch {
    return codeDataUri(FIXTURE.ticket.number);
  }
})();

const DARK = {
  colors: { background: "#14532d", foreground: "#ffffff", muted: "#cfe0d4" },
};

export default function TicketEmail({ fixture = FIXTURE }: { fixture?: Fixture }) {
  const { home, away, ticket } = fixture;
  return (
    <Email
      width={600}
      theme={homeTheme}
      lang="en"
      title={`${home.short} v ${away.short} — your match ticket`}
      previewText={`Your ${home.name} ticket — ${ticket.stand}, Row ${ticket.row}, Seat ${ticket.seat}. ${fixture.date}, kickoff ${fixture.kickoff}.`}
      fonts={WEB_FONT_FACES}
      style={{ gap: 0 }}
    >
      {/* Header band: the fixture, on pine. */}
      <Section tokens={DARK} style={{ padding: [28, 24], gap: 18 }}>
        <Text style={{ apply: ["label"], color: "#cfe0d4" }}>
          {fixture.competition} · Matchday {fixture.matchday}
        </Text>
        <Row style={{ gap: 16, alignItems: "center" }}>
          <Column>
            <TeamBadge name={home.name} short={home.short} founded={home.founded} color={home.color} />
          </Column>
          <Text
            style={{
              flex: "none",
              fontFamily: "'Barlow Condensed', 'Arial Narrow', sans-serif",
              fontWeight: 700,
              fontSize: 26,
              color: "#c9a227",
            }}
          >
            VS
          </Text>
          <Column style={{ alignItems: "end" }}>
            <TeamBadge name={away.name} short={away.short} founded={away.founded} color={away.color} />
          </Column>
        </Row>
        <Text style={{ fontSize: 14, color: "#cfe0d4" }}>
          {fixture.date} · Kickoff {fixture.kickoff} · {fixture.venue}, {fixture.city}
        </Text>
      </Section>

      {/* Greeting + ticket card. */}
      <Section style={{ padding: [28, 24], gap: 20 }}>
        <Column style={{ gap: 8 }}>
          <Heading level={1}>Your ticket for Saturday</Heading>
          <Text>
            Hello <MergeTag name="first_name" />, your seat is waiting at {fixture.venue}. Show the
            code below at Gate {ticket.gate} — no printing needed, your phone is enough.
          </Text>
        </Column>

        <Column style={{ apply: ["card"] }}>
          <Row style={{ gap: 20, alignItems: "start" }}>
            <Column style={{ gap: 6 }}>
              <Text style={{ apply: ["label"] }}>Admit one · {fixture.competition}</Text>
              <Text style={{ fontFamily: "'Barlow Condensed', 'Arial Narrow', sans-serif", fontWeight: 700, fontSize: 30, lineHeight: 1 }}>
                {ticket.holder}
              </Text>
              <Text style={{ fontFamily: "'IBM Plex Mono', monospace", fontSize: 12, fontWeight: 700, letterSpacing: 1 }}>
                {ticket.number}
              </Text>
              <Text style={{ fontSize: 13, color: token("colors.muted") }}>
                {home.name} v {away.name} · {ticket.price}
              </Text>
            </Column>
            <Column style={{ gap: 6, alignItems: "center" }}>
              <Image
                src={{ src: CODE_SRC, width: 232, height: 232 }}
                alt={`Ticket code ${ticket.number} — show at the gate`}
                style={{ width: 148 }}
              />
              <Text style={{ fontFamily: "'IBM Plex Mono', monospace", fontSize: 10, letterSpacing: 1, textAlign: "center" }}>
                SHOW AT GATE {ticket.gate}
              </Text>
            </Column>
          </Row>
          <Divider />
          <Grid columns={4} style={{ gap: 16 }}>
            <InfoPill label="Stand" value={ticket.stand} />
            <InfoPill label="Row" value={ticket.row} />
            <InfoPill label="Seat" value={ticket.seat} />
            <InfoPill label="Gate" value={ticket.gate} />
          </Grid>
        </Column>

        <Column style={{ gap: 10 }}>
          <Heading level={2}>Getting there</Heading>
          <List style={{ gap: 6, fontSize: 14, lineHeight: 1.5 }}>
            <ListItem>
              Tram: the Dockside line to {fixture.venue} Halt — four minutes on foot from the stop.
            </ListItem>
            <ListItem>Gates open at 13:30. Arrive by 14:30 to catch the teams warming up.</ListItem>
            <ListItem>Bring photo ID that matches the name on the ticket.</ListItem>
          </List>
        </Column>

        <Button href="https://northgate.example/matchday-14">View the match centre</Button>
      </Section>

      {/* Footer. */}
      <Section style={{ padding: [8, 24, 28], gap: 14 }}>
        <Divider />
        <Menu
          items={[
            { text: "Tickets", href: "https://northgate.example/tickets" },
            { text: "Fixtures", href: "https://northgate.example/fixtures" },
            { text: "Club shop", href: "https://northgate.example/shop" },
          ]}
          style={{ justifyContent: "center" }}
        />
        <Social
          icons={[
            { name: "Instagram", href: "https://northgate.example/instagram" },
            { name: "X", href: "https://northgate.example/x" },
          ]}
          style={{ justifyContent: "center" }}
        />
        <Text style={{ fontSize: 12, color: token("colors.muted"), textAlign: "center" }}>
          Northgate Rovers FC · {fixture.venue}, {fixture.city} NG4 2QT ·{" "}
          <Link href="https://northgate.example/unsubscribe">Unsubscribe</Link> ·{" "}
          <Span>Tickets are non-transferable.</Span>
        </Text>
      </Section>
    </Email>
  );
}
